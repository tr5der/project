"""Werkzeug-compatible scrypt password hashes, using only Python's standard library.

Supports hashes generated by the attached project (`scrypt:32768:8:1$salt$hash`).
"""
import hashlib
import hmac
import secrets


def generate_password_hash(password):
    salt = secrets.token_urlsafe(12)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt.encode("utf-8"), n=32768, r=8, p=1, maxmem=128*1024*1024)
    return f"scrypt:32768:8:1${salt}${digest.hex()}"


def check_password_hash(encoded, password):
    try:
        method, salt, expected = encoded.split("$", 2)
        algo, n, r, p = method.split(":")
        if algo != "scrypt" or (int(n), int(r), int(p)) != (32768, 8, 1):
            return False
        derived = hashlib.scrypt(password.encode("utf-8"), salt=salt.encode("utf-8"), n=32768, r=8, p=1, maxmem=128*1024*1024)
        return hmac.compare_digest(derived.hex(), expected)
    except (ValueError, TypeError, AttributeError):
        return False
